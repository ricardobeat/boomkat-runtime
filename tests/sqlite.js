import { Database, Statement, version } from "sqlite";
const assert = (ok, message) => { if (!ok) throw new Error(message); };
const throws = (fn, message) => { let thrown = false; try { fn(); } catch (_) { thrown = true; } assert(thrown, message); };
assert(typeof version === "string", "SQLite version missing");
const db = new Database();
db.exec("CREATE TABLE t (id INTEGER PRIMARY KEY, name TEXT UNIQUE, data BLOB, n INTEGER); CREATE INDEX names ON t(name);");
const insert = db.prepare("INSERT INTO t(name, data, n) VALUES (?, ?, ?)");
const result = insert.run("café😀", new Uint8Array([0, 1, 255]), 42);
assert(result.changes === 1 && result.lastInsertRowid === 1, "insert stats wrong");
insert.run(["second", new Uint8Array(0), -9223372036854775808n]);
insert.run("nul\0text", null, 9223372036854775807n);
const rows = db.query("SELECT * FROM t ORDER BY id");
const all = rows.all();
assert(all.length === 3 && all[0].name === "café😀", "rows or UTF-8 wrong");
assert(Object.getPrototypeOf(all[0]) === null, "rows must be safe dictionaries");
assert(all[0].data instanceof Uint8Array && all[0].data.join() === "0,1,255", "blob wrong");
assert(all[1].data.length === 0 && all[1].data !== null, "empty blob became null");
assert(all[2].name === "nul\0text" && all[2].data === null, "text NUL or null wrong");
assert(all[1].n === -9223372036854775808n && all[2].n === 9223372036854775807n, "int64 precision lost");
assert(rows.all()[0].data.join() === "0,1,255", "blob result did not survive statement reuse");
const named = db.query("SELECT id FROM t WHERE name = :name OR id = $id");
assert(named.get({ name: "second", id: 99 }).id === 2, "bare named binding wrong");
assert(named.get({ ":name": "missing", "$id": 1 }).id === 1, "prefixed named binding wrong");
assert(named.get({ name: "missing", id: 99 }) === undefined, "get should return undefined on no match");
throws(() => named.get({ name: "second" }), "missing binding accepted");
throws(() => named.get({ name: "second", id: 0, extra: 1 }), "extra binding accepted");
throws(() => insert.run(1), "wrong parameter count accepted");
throws(() => insert.run("bad", {}, 1), "object binding accepted");
throws(() => insert.run("bad", null, 9223372036854775808n), "overflow BigInt accepted");
throws(() => insert.run("bad", null, NaN), "NaN accepted");
throws(() => db.prepare("SELECT 1; SELECT 2"), "multiple prepared statements accepted");
throws(() => db.exec("SELECT 1\0; CREATE TABLE hidden(x)"), "NUL SQL accepted");
assert(db.query("SELECT 1; -- trailing comment").get()["1"] === 1, "trailing comment rejected");
throws(() => new Statement(), "statement constructor exposed native handles");
const count = db.query("SELECT COUNT(*) AS n FROM t");
const transaction = db.transaction(name => insert.run(name, null, 1));
transaction("third");
assert(count.get().n === 4, "transaction did not commit");
throws(db.transaction(() => { insert.run("rollback", null, 1); throw new Error("rollback"); }), "transaction error swallowed");
assert(count.get().n === 4, "transaction did not roll back");
db.transaction(() => { transaction("nested"); })();
assert(count.get().n === 5, "nested savepoint failed");
throws(db.transaction(async () => { insert.run("async", null, 1); }), "async transaction accepted");
assert(count.get().n === 5, "async transaction did not roll back");
const originalError = __bk.error;
let errorEntries = 0;
__bk.error = () => { errorEntries++; db.close(); };
let constraint;
try { insert.run("second", null, 1); } catch (error) { constraint = error; }
__bk.error = originalError;
assert(errorEntries === 0, "error construction re-entered JS");
assert(constraint && constraint.code === "SQLITE_2067", "extended error code missing");
insert.run("after error", null, 1);
assert(count.get().n === 6, "statement not reusable after failure");
for (const sql of ["ATTACH ':memory:' AS other", "VACUUM INTO '/tmp/sqlite-escape.db'", "PRAGMA TEMP_STORE_DIRECTORY='/tmp'", "PRAGMA temp_store=FILE", "SELECT load_extension('/tmp/libbad')"])
    throws(() => db.exec(sql), "file bypass accepted: " + sql);
const unsafe = db.query('SELECT 1 AS "__proto__"').get();
assert(unsafe.__proto__ === 1 && Object.getPrototypeOf(unsafe) === null, "column polluted prototype");
rows.finalize(); rows.finalize();
throws(() => rows.all(), "finalized statement usable");
const invalidated = db.query("SELECT 1");
db.close(); db.close();
throws(() => invalidated.all(), "statement survived database close");
invalidated.finalize();
throws(() => db.exec("SELECT 1"), "closed database usable");
const reentrant = new Database();
const victim = reentrant.prepare("SELECT :x");
throws(() => victim.get({ get x() { reentrant.close(); return 1; } }), "binding getter closed a borrowed native handle");
// Cleanup must also finalize outstanding statements at normal process exit.
const remaining = new Database();
remaining.query("SELECT 1");
console.log("sqlite: passed (" + version + ")");
